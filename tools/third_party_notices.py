"""Write THIRD-PARTY-NOTICES.md: every Python package the portable build ships
(requirements.lock) with its version, license and home page, read from the
installed metadata of the dev venv. Run it whenever requirements.lock changes:

    .venv/Scripts/python.exe tools/third_party_notices.py

Licenses that are not known to be compatible with GPL-3.0 are listed at the
end for a manual check (the script exits with 1 if there are any).
"""
from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "THIRD-PARTY-NOTICES.md"

# License families that can be combined with GPL-3.0 in one program.
GPL3_COMPATIBLE = [
    "MIT", "BSD", "Apache", "ISC", "PSF", "Python Software Foundation", "Python-2.0", "MPL-2.0",
    "Mozilla Public License 2.0", "LGPL", "GPL-3.0", "GPLv3", "GPL-2.0-or-later", "Unlicense", "CC0",
    "Zlib", "zlib", "HPND", "Historical Permission Notice", "0BSD", "Public Domain", "WTFPL",
]
# Classifier → short name, for packages that only declare a classifier.
CLASSIFIERS = {
    "MIT License": "MIT", "BSD License": "BSD", "Apache Software License": "Apache-2.0",
    "ISC License (ISCL)": "ISC", "Python Software Foundation License": "PSF-2.0",
    "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0",
    "GNU Lesser General Public License v3 (LGPLv3)": "LGPL-3.0",
    "GNU Lesser General Public License v2 or later (LGPLv2+)": "LGPL-2.0-or-later",
    "Historical Permission Notice and Disclaimer (HPND)": "HPND",
    "The Unlicense (Unlicense)": "Unlicense",
}


def locked_packages() -> list[str]:
    names = []
    for line in (REPO / "requirements.lock").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)(\[[^\]]*\])?==", line)
        if m:
            names.append(m.group(1))
    return sorted(set(names), key=str.lower)


def license_of(meta) -> str:
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    from_classifiers = [CLASSIFIERS.get(c.split(" :: ")[-1], c.split(" :: ")[-1])
                        for c in meta.get_all("Classifier") or [] if c.startswith("License :: OSI Approved")]
    if from_classifiers:
        return " / ".join(dict.fromkeys(from_classifiers))
    text = (meta.get("License") or "").strip()
    if text:
        first = text.splitlines()[0].strip()
        return first if len(first) <= 60 else first[:57] + "…"
    return "UNKNOWN"


def homepage(meta) -> str:
    if meta.get("Home-page"):
        return meta["Home-page"]
    for url in meta.get_all("Project-URL") or []:
        label, _, link = url.partition(",")
        if label.strip().lower() in ("homepage", "home", "source", "source code", "repository"):
            return link.strip()
    urls = meta.get_all("Project-URL") or []
    return urls[0].partition(",")[2].strip() if urls else ""


def main() -> int:
    rows, missing, check = [], [], []
    for name in locked_packages():
        try:
            meta = metadata.metadata(name)
        except metadata.PackageNotFoundError:
            missing.append(name)
            continue
        lic = license_of(meta)
        rows.append((meta["Name"], meta["Version"], lic, homepage(meta)))
        if not any(token.lower() in lic.lower() for token in GPL3_COMPATIBLE):
            check.append((meta["Name"], lic))

    py = sys.version.split()[0]
    lines = [
        "# Third-party notices",
        "",
        "Nomad Studio is licensed under GPL-3.0-or-later (see [LICENSE](LICENSE) and [LICENSING.md](LICENSING.md)).",
        "The portable build also ships the following software, each under its own license.",
        "Generated by `tools/third_party_notices.py` from `requirements.lock`; do not edit by hand.",
        "",
        "## Runtime",
        "",
        "| Component | Version | License | Home page |",
        "|---|---|---|---|",
        f"| CPython | {py} | PSF-2.0 | https://www.python.org/ |",
        "",
        "## Python packages",
        "",
        "| Package | Version | License | Home page |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {v} | {l.replace('|', '/')} | {h} |" for n, v, l, h in rows]
    lines += [
        "",
        "## Web assets (app/static/vendor)",
        "",
        "Served by the app itself, so it works offline and makes no requests to third parties.",
        "",
        "| Asset | License | Home page |",
        "|---|---|---|",
        "| Lucide icons 1.49.0 (`vendor/lucide`) | ISC — `vendor/lucide/LICENSE` | https://lucide.dev/ |",
        "| Asap font (`vendor/fonts`) | SIL OFL 1.1 — `vendor/fonts/Asap-OFL.txt` | https://github.com/Omnibus-Type/Asap |",
        "| Fugaz One font (`vendor/fonts`) | SIL OFL 1.1 — `vendor/fonts/FugazOne-OFL.txt` | https://fonts.google.com/specimen/Fugaz+One |",
        "",
        "## Not included",
        "",
        "ComfyUI (GPL-3.0) and LM Studio are separate programs the user installs; Nomad Studio talks to them",
        "over their local HTTP APIs. AI models are downloaded by the user and keep their own licenses.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(rows)} packages")
    if missing:
        print("not installed in this venv (license not read):", ", ".join(missing))
    if check:
        print("check by hand (not known to be GPL-3.0 compatible):")
        for n, l in check:
            print(f"  {n}: {l}")
    return 1 if missing or check else 0


if __name__ == "__main__":
    sys.exit(main())
